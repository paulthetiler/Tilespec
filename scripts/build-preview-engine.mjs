// Bundles the REAL Next Action engine (lib/operations/next-actions) for the clickable preview,
// so the preview and the application run the same code and cannot drift apart.
//   node scripts/build-preview-engine.mjs          write docs/redesign/prototype/engine.js
//   node scripts/build-preview-engine.mjs --check  fail if the committed bundle is out of date
import { build } from "esbuild";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "docs/redesign/prototype/engine.js");
const result = await build({
  entryPoints: [path.join(root, "lib/operations/next-actions/index.ts")],
  bundle: true, format: "iife", globalName: "TSEngine", target: "es2019", legalComments: "none", write: false,
  banner: { js: "/* GENERATED by scripts/build-preview-engine.mjs from lib/operations/next-actions. Do not edit by hand. */" },
  define: { "process.env": "{}" },
  logLevel: "silent",
});
const code = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== code) { console.error("docs/redesign/prototype/engine.js is out of date. Run: node scripts/build-preview-engine.mjs"); process.exit(1); }
  console.log("preview engine is up to date");
} else { writeFileSync(out, code); console.log(`wrote ${path.relative(root, out)} (${code.length} bytes)`); }
